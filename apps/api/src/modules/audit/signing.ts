import {
  createHash,
  createPrivateKey,
  createPublicKey,
  generateKeyPairSync,
  sign as edSign,
  verify as edVerify,
  type KeyObject,
} from 'node:crypto';
import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { loggerFor } from '../../observability/logger.js';

const log = loggerFor('signing');

/**
 * Signs the hash list of an export packet with Ed25519.
 *
 * The private key is a development key: generated once (by `make up`, or on first use when none exists outside
 * production) into `infra/dev-keys/`, which is git-ignored. In production it would be held in an HSM or wrapped by a
 * KMS and never sit on disk next to the application; `loadSigner` refuses to invent a key there.
 */
export interface ExportSigner {
  /** SPKI PEM, shipped inside every packet so a copy can be checked without asking anyone. */
  publicKeyPem: string;
  /** The same key as base64 SPKI DER, for the manifest. */
  publicKeyBase64: string;
  /** SHA-256 of the SPKI DER: recorded in the audit log, so a swapped key inside a packet is detectable. */
  fingerprint: string;
  sign(data: Uint8Array): Buffer;
}

export const DEFAULT_DEV_KEY_FILE = path.resolve(
  import.meta.dirname,
  '../../../../../infra/dev-keys/audit-export-ed25519.pem',
);

export function signerFromKey(privateKey: KeyObject): ExportSigner {
  const publicKey = createPublicKey(privateKey);
  const der = publicKey.export({ type: 'spki', format: 'der' });
  return {
    publicKeyPem: publicKey.export({ type: 'spki', format: 'pem' }).toString(),
    publicKeyBase64: der.toString('base64'),
    fingerprint: createHash('sha256').update(der).digest('hex'),
    sign: (data) => edSign(null, data, privateKey),
  };
}

/** A throwaway signer for tests. */
export const createEphemeralSigner = (): ExportSigner =>
  signerFromKey(generateKeyPairSync('ed25519').privateKey);

export function loadSigner(opts: {
  keyFile?: string | undefined;
  production: boolean;
}): ExportSigner {
  const file = opts.keyFile ?? DEFAULT_DEV_KEY_FILE;
  if (!existsSync(file)) {
    if (opts.production) {
      throw new Error(
        `AUDIT_SIGNING_KEY_FILE (${file}) does not exist. In production the export signing key must be provisioned ` +
          '(HSM- or KMS-backed); it is never generated by the application.',
      );
    }
    mkdirSync(path.dirname(file), { recursive: true });
    const { privateKey } = generateKeyPairSync('ed25519');
    writeFileSync(file, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });
    chmodSync(file, 0o600);
    log.info({ file }, 'generated a development export signing key');
  }
  return signerFromKey(createPrivateKey(readFileSync(file)));
}

/** Verifies `signature` over `data` with an SPKI base64 key: what `verify.sh` does with OpenSSL, in Node. */
export function verifySignature(
  publicKeyBase64: string,
  data: Uint8Array,
  signature: Uint8Array,
): boolean {
  try {
    const key = createPublicKey({
      key: Buffer.from(publicKeyBase64, 'base64'),
      type: 'spki',
      format: 'der',
    });
    return edVerify(null, data, key, signature);
  } catch {
    return false;
  }
}
